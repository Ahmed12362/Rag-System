package com.mimocodes.hrisrag.document.corpus;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.ai.chat.messages.SystemMessage;
import org.springframework.ai.chat.messages.UserMessage;
import org.springframework.ai.chat.metadata.Usage;
import org.springframework.ai.chat.model.ChatModel;
import org.springframework.ai.chat.model.ChatResponse;
import org.springframework.ai.chat.prompt.Prompt;

import com.mimocodes.hrisrag.config.ChatOptionsFactory;

/**
 * Generates corpus documents with a chat model through Spring AI's provider-neutral ChatModel.
 * <ul>
 * <li>Resume: a document whose file already validates is skipped (no API call).</li>
 * <li>Transient provider errors (429/5xx, "unavailable", "overloaded") are retried with exponential backoff.</li>
 * <li>Quota: when a model's quota is exhausted (a per-day quota error, or 429s persisting after all retries), the next model
 * of the fallback chain is used. When every model is exhausted the run stops cleanly; remaining documents are reported as
 * NOT_ATTEMPTED and can be generated by a later run.</li>
 * <li>A draft that fails validation is regenerated with the validator's messages as feedback.</li>
 * <li>Only validated documents are written to the corpus; rejected drafts go to a separate folder for inspection.</li>
 * </ul>
 * Run with {@code --spring.ai.retry.max-attempts=1} so Spring AI's own retry (10 attempts, x5 backoff) does not hide
 * quota errors for minutes.
 */
public class CorpusGenerator {

	private static final Logger log = LoggerFactory.getLogger(CorpusGenerator.class);

	/** Abstracted so tests do not really wait. */
	@FunctionalInterface
	public interface Sleeper {
		void sleep(long millis);
	}

	public enum Status { SKIPPED_VALID, GENERATED, FAILED, NOT_ATTEMPTED }

	public record Outcome(PlannedDocument plan, Status status, String model, int apiCalls, List<String> lastErrors,
			Integer promptTokens, Integer completionTokens, Integer thinkingTokens, long latencyMs) {
	}

	private record Draft(String body, String model, Integer promptTokens, Integer completionTokens,
			Integer thinkingTokens, long latencyMs, int calls, String finishReason) {
	}

	/**
	 * Why the provider stopped generating. STOP = the model finished on its own. UNKNOWN = no finish reason reported
	 * (logged, not blocking: structural validation still catches truncation). Every other category blocks the draft.
	 */
	enum StopCategory { STOP, UNKNOWN, RECITATION, SAFETY, MAX_TOKENS, OTHER;

		boolean blocksDraft() {
			return this != STOP && this != UNKNOWN;
		}
	}

	static StopCategory classify(String finishReason) {
		if (finishReason == null || finishReason.isBlank()) {
			return StopCategory.UNKNOWN;
		}
		String r = finishReason.toUpperCase(Locale.ROOT);
		if (r.equals("STOP") || r.equals("FINISH_REASON_STOP")) {
			return StopCategory.STOP;
		}
		if (r.contains("RECITATION")) {
			return StopCategory.RECITATION;
		}
		if (r.contains("SAFETY") || r.contains("PROHIBITED") || r.contains("BLOCKLIST") || r.contains("SPII")) {
			return StopCategory.SAFETY;
		}
		if (r.contains("MAX_TOKENS") || r.contains("LENGTH")) {
			return StopCategory.MAX_TOKENS;
		}
		return StopCategory.OTHER;
	}

	/** Every model of the fallback chain has exhausted its quota. */
	static final class AllModelsExhaustedException extends RuntimeException {
		AllModelsExhaustedException(String message) {
			super(message);
		}
	}

	private final ChatModel chatModel;
	private final ChatOptionsFactory optionsFactory;
	private final CorpusProperties props;
	private final PromptBuilder prompts;
	private final CorpusDocumentValidator validator;
	private final Sleeper sleeper;
	private int modelIndex;

	public CorpusGenerator(ChatModel chatModel, ChatOptionsFactory optionsFactory, CorpusProperties props,
			PromptBuilder prompts, CorpusDocumentValidator validator, Sleeper sleeper) {
		if (props.models() == null || props.models().isEmpty()) {
			throw new IllegalArgumentException("at least one generation model is required");
		}
		this.chatModel = chatModel;
		this.optionsFactory = optionsFactory;
		this.props = props;
		this.prompts = prompts;
		this.validator = validator;
		this.sleeper = sleeper;
	}

	public List<Outcome> generate(CorpusSpec spec, List<PlannedDocument> selection, Path corpusRoot, Path rejectedRoot) {
		CorpusManifest manifest = CorpusManifest.load(corpusRoot);
		List<Outcome> outcomes = new ArrayList<>();
		boolean exhausted = false;
		int i = 0;
		for (PlannedDocument plan : selection) {
			i++;
			Outcome outcome;
			if (exhausted) {
				outcome = new Outcome(plan, Status.NOT_ATTEMPTED, null, 0, List.of("all models exhausted"), null, null,
						null, 0);
			}
			else {
				try {
					outcome = generateOne(spec, plan, corpusRoot, rejectedRoot, manifest);
				}
				catch (AllModelsExhaustedException e) {
					log.error("Stopping: {}. Re-run later to resume.", e.getMessage());
					exhausted = true;
					outcome = new Outcome(plan, Status.NOT_ATTEMPTED, null, 0, List.of(e.getMessage()), null, null, null,
							0);
				}
			}
			outcomes.add(outcome);
			log.info("[{}/{}] {} {} model={} (api calls: {}){}", i, selection.size(), outcome.status(), plan.id(),
					outcome.model(), outcome.apiCalls(),
					outcome.lastErrors().isEmpty() ? "" : " errors=" + outcome.lastErrors());
			manifest.save(); // persist progress after every document so an interrupted run can resume
		}
		return outcomes;
	}

	public String currentModel() {
		return props.models().get(modelIndex);
	}

	private Outcome generateOne(CorpusSpec spec, PlannedDocument plan, Path corpusRoot, Path rejectedRoot,
			CorpusManifest manifest) {
		Path target = corpusRoot.resolve(plan.relativePath());
		if (Files.exists(target) && validator.validateFile(plan, read(target), spec.facts()).isEmpty()) {
			return new Outcome(plan, Status.SKIPPED_VALID, null, 0, List.of(), null, null, null, 0);
		}

		List<String> feedback = List.of();
		int calls = 0;
		Draft draft = null;
		for (int attempt = 0; attempt <= props.maxFeedbackAttempts(); attempt++) {
			try {
				draft = callWithRetryAndFallback(plan, spec, feedback);
			}
			catch (AllModelsExhaustedException e) {
				throw e;
			}
			catch (RuntimeException e) {
				return new Outcome(plan, Status.FAILED, currentModel(), calls + 1,
						List.of("provider error: " + e.getMessage()), null, null, null, 0);
			}
			calls += draft.calls();
			String body = draft.body().strip() + "\n";
			feedback = new ArrayList<>();
			StopCategory stop = classify(draft.finishReason());
			if (stop == StopCategory.UNKNOWN) {
				log.warn("{}: provider reported no finish reason; relying on structural validation", plan.id());
			}
			if (stop.blocksDraft()) {
				// Never accept a draft the provider did not finish, even if it happened to pass the other checks.
				feedback.add("Provider stopped early: " + stop + " (finish reason: " + draft.finishReason() + ").");
			}
			feedback.addAll(validator.validateBody(plan, body, spec.facts()));
			if (feedback.isEmpty()) {
				write(target, plan.metadata().toFrontMatter() + body);
				manifest.put(plan.relativePath(), new CorpusManifest.Entry(plan.metadata().docKey(),
						plan.metadata().version(), plan.metadata().language(), plan.group(), CorpusManifest.sha256(target),
						draft.model(), draft.promptTokens(), draft.completionTokens(), draft.thinkingTokens(),
						draft.latencyMs(), calls));
				return new Outcome(plan, Status.GENERATED, draft.model(), calls, List.of(), draft.promptTokens(),
						draft.completionTokens(), draft.thinkingTokens(), draft.latencyMs());
			}
			write(rejectedRoot.resolve(plan.relativePath() + ".attempt" + (attempt + 1)), body);
		}
		return new Outcome(plan, Status.FAILED, draft.model(), calls, feedback, draft.promptTokens(),
				draft.completionTokens(), draft.thinkingTokens(), draft.latencyMs());
	}

	/** Calls the current model; on quota exhaustion moves down the fallback chain, retrying the same request. */
	private Draft callWithRetryAndFallback(PlannedDocument plan, CorpusSpec spec, List<String> feedback) {
		String userPrompt = prompts.userPrompt(plan, spec.facts(), feedback);
		int calls = 0;
		while (true) {
			String model = currentModel();
			try {
				Draft d = callWithRetry(plan, model, userPrompt);
				return new Draft(d.body(), d.model(), d.promptTokens(), d.completionTokens(), d.thinkingTokens(),
						d.latencyMs(), calls + d.calls(), d.finishReason());
			}
			catch (QuotaExhausted q) {
				calls += q.calls;
				if (modelIndex + 1 >= props.models().size()) {
					throw new AllModelsExhaustedException("quota exhausted for all models " + props.models());
				}
				modelIndex++;
				log.warn("{}: quota exhausted for {}, switching to {}", plan.id(), model, currentModel());
			}
		}
	}

	/** Internal signal: the given model's quota is used up. */
	private static final class QuotaExhausted extends RuntimeException {
		final int calls;

		QuotaExhausted(int calls, Throwable cause) {
			super(cause);
			this.calls = calls;
		}
	}

	private Draft callWithRetry(PlannedDocument plan, String model, String userPrompt) {
		double temperature = plan.temperature() != null ? plan.temperature() : props.temperature();
		Prompt prompt = new Prompt(
				List.of(new SystemMessage(PromptBuilder.SYSTEM_PROMPT), new UserMessage(userPrompt)),
				optionsFactory.create(model, temperature));
		long backoff = props.initialBackoffMs();
		for (int attempt = 1;; attempt++) {
			sleeper.sleep(props.delayMs()); // pacing between provider calls
			long start = System.nanoTime();
			try {
				ChatResponse response = chatModel.call(prompt);
				long latency = (System.nanoTime() - start) / 1_000_000;
				String text = response.getResult().getOutput().getText();
				Usage usage = response.getMetadata() == null ? null : response.getMetadata().getUsage();
				Integer promptTokens = usage == null ? null : usage.getPromptTokens();
				Integer completion = usage == null ? null : usage.getCompletionTokens();
				Integer thinking = null;
				if (usage != null && usage.getTotalTokens() != null && promptTokens != null && completion != null) {
					int extra = usage.getTotalTokens() - promptTokens - completion;
					thinking = extra > 0 ? extra : 0;
				}
				String finishReason = response.getResult().getMetadata() == null ? null
						: response.getResult().getMetadata().getFinishReason();
				log.info("{} [{}] response: finishReason={} ({}) temperature={} id={} tokens(p/c/t)={}/{}/{} "
						+ "latency={}ms chars={} generationMetadata={}", plan.id(), model, finishReason,
						classify(finishReason), temperature,
						response.getMetadata() == null ? null : response.getMetadata().getId(), promptTokens,
						completion, thinking, latency, text == null ? 0 : text.length(),
						response.getResult().getMetadata());
				return new Draft(text == null ? "" : text, model, promptTokens, completion, thinking, latency, attempt,
						finishReason);
			}
			catch (RuntimeException e) {
				if (isDailyQuota(e)) {
					throw new QuotaExhausted(attempt, e);
				}
				if (!isTransient(e)) {
					throw e;
				}
				if (attempt > props.maxTransientRetries()) {
					if (isRateLimit(e)) {
						throw new QuotaExhausted(attempt, e); // 429 that never clears: treat as exhausted quota
					}
					throw e;
				}
				log.warn("{} [{}]: transient provider error (attempt {}), retrying in {} ms: {}", plan.id(), model,
						attempt, backoff, e.getMessage());
				sleeper.sleep(backoff);
				backoff *= 2;
			}
		}
	}

	/** 429 / 5xx style failures that are worth retrying. Walks the cause chain. */
	static boolean isTransient(Throwable e) {
		return anyMessage(e, "429", "500", "502", "503", "504", "unavailable", "overloaded", "resource_exhausted",
				"high demand", "timeout", "timed out", "quota");
	}

	static boolean isRateLimit(Throwable e) {
		return anyMessage(e, "429", "resource_exhausted", "quota");
	}

	/** Google reports daily free-tier limits with quota ids such as "GenerateRequestsPerDayPerProjectPerModel". */
	static boolean isDailyQuota(Throwable e) {
		return anyMessage(e, "perday", "per day", "requests per day");
	}

	private static boolean anyMessage(Throwable e, String... needles) {
		for (Throwable t = e; t != null; t = t.getCause()) {
			String m = String.valueOf(t.getMessage()).toLowerCase(Locale.ROOT);
			for (String n : needles) {
				if (m.contains(n)) {
					return true;
				}
			}
		}
		return false;
	}

	private static String read(Path file) {
		try {
			return Files.readString(file, StandardCharsets.UTF_8);
		}
		catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	private static void write(Path file, String content) {
		try {
			Files.createDirectories(file.getParent());
			Files.writeString(file, content, StandardCharsets.UTF_8);
		}
		catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}
}
